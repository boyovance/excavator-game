const { app, nativeTheme } = require('electron');
const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { bannerScript } = require('./demo-banner.cjs');
const { wait, requireIsolatedProfile, watchWindows, makeUntil, makeShot, adminReplace, pageScript } = require('./lib/harness.cjs');
const demo = process.env.EXCAVATOR_DISPATCH_DEMO === '1';
const output = process.env.EXCAVATOR_DISPATCH_OUTPUT;
requireIsolatedProfile('exc-dispatch-');
nativeTheme.themeSource = 'light';
const errors = watchWindows(app, { hide: !demo });
require('../electron/main.cjs');
const ctx = require('../electron/context.cjs');
const backend = require('../electron/server.cjs');
const { openGarage } = require('../electron/windows.cjs');
const { updateSettings } = require('../electron/settings.cjs');
const until = makeUntil('dispatch UI');
(async () => {
  await app.whenReady();
  await until(() => ctx.win && ctx.gameState && !ctx.win.webContents.isLoading());
  openGarage('garage');
  await until(() => ctx.garageWin && !ctx.garageWin.webContents.isLoading());
  const g = ctx.garageWin.webContents;
  const p = ctx.win.webContents;
  const js = pageScript(() => g);
  const scene = (code) => p.executeJavaScript(code);
  await until(() => js('!!document.querySelector("[data-site=yard]")'));
  await until(() => scene('!!window.__excavator?.sprite'));
  const replace = (state) => adminReplace(backend.call, state);
  // Existing game art and production renderer, deterministic test rewards only.
  await replace({ ...ctx.gameState, name: '派遣測試', coins: 120, xp: 0, durability: 100, owned: [...ctx.gameState.owned, 'stick_long', 'acc_beacon'], equipped: { ...ctx.gameState.equipped, stick: 'stick_long' } });
  await until(() => js('document.querySelector("#pet-name").value === "派遣測試"'));
  await js(bannerScript('派遣驗收演示 · 獨立測試存檔 · 測試已加速計時，不影響正式進度'));
  ctx.garageWin.setTitle('派遣驗收演示 — 不影響正式存檔');
  const focusJobs = () => js('document.querySelector("#jobs").closest("section").scrollIntoView(); window.scrollBy(0,-38)');
  const shot = makeShot(() => g, output);
  const originalSize = ctx.garageWin.getContentSize();
  for (const width of [originalSize[0], 380]) {
    ctx.garageWin.setContentSize(width, originalSize[1]);
    await wait(100);
    await js('window.scrollTo(0,0)');
    assert(await js(`(() => {
      const badge = document.querySelector('[data-demo-banner]').getBoundingClientRect();
      const header = document.querySelector('header').getBoundingClientRect();
      return badge.bottom <= header.top && document.documentElement.scrollWidth <= innerWidth &&
        [...document.querySelectorAll('header button')].every(button => {
          const box = button.getBoundingClientRect();
          return button.contains(document.elementFromPoint(box.x + box.width / 2, box.y + box.height / 2));
        });
    })()`), `Demo notice must not cover header controls at width ${width}`);
    await shot(width === 380 ? '00-header-narrow' : '00-header');
  }
  ctx.garageWin.setContentSize(...originalSize);
  console.log('PASS Demo notice: normal and narrow windows keep header controls unobstructed');
  await focusJobs(); await shot('01-sites');
  await js('document.querySelector("[data-site=yard]").click()');
  assert(await js('document.querySelector("#job-confirm").open'));
  assert(await js('document.querySelector("#job-confirm-body").textContent.includes("×1.15")'));
  await shot('02-confirm');
  await js('document.querySelector("#job-depart").click(); document.querySelector("#job-depart").click()');
  await until(() => ctx.gameState.jobs[0] && js('!!document.querySelector("[data-job=cancel]")'));
  const original = ctx.gameState.jobs[0];
  assert.equal(original.equippedSnapshot.stick, 'stick_long');
  assert.equal((await js('window.api.requestAction({type:"claim",jobId:' + JSON.stringify(original.id) + '})')).ok, false);
  await until(() => scene('window.__excavator.debugState().state === "working"'));
  await focusJobs(); await shot('03-running');
  const now = Date.now();
  await replace({ ...ctx.gameState, jobs: [{ ...original, start: now - 299_000, end: now + 1000, rolls: [0.5, 0.5, 0.99, 0.01, 0, 0.99, 0, 0.99, 0, 0.99, 0] }] });
  await until(() => js('!!document.querySelector("[data-job=claim]")'));
  await until(() => scene('window.__excavator.debugState().state === "waiting"'));
  const before = ctx.gameState.coins;
  await wait(1200);
  assert.equal(ctx.gameState.coins, before);
  assert(ctx.gameState.jobs[0], 'scene must not claim automatically');
  assert.equal(await js('!!document.querySelector("[data-job=cancel]")'), false);
  await focusJobs(); await shot('04-ready');
  // Capture the existing 2D pet and its actual completion label.
  const crop = await scene(`(() => { const s=window.__excavator.sprite; return {x:Math.max(0,Math.floor(s.x-190)),y:Math.max(0,Math.floor(s.y-220)),width:380,height:220}; })()`);
  fs.writeFileSync(path.join(output, '05-pet-ready.png'), (await p.capturePage(crop)).toPNG());
  // The real save writer fails; UI must retain the claim button and show a failure, not a success.
  const blocked = path.join(app.getPath('userData'), 'state.json.tmp');
  fs.mkdirSync(blocked);
  await js('document.querySelector("[data-job=claim]").click()');
  await until(() => js('document.querySelector("#job-message").textContent.includes("存檔失敗")'));
  assert.equal(ctx.gameState.coins, before);
  assert(ctx.gameState.jobs[0]);
  fs.rmdirSync(blocked);
  await js('document.querySelector("[data-job=claim]").click(); document.querySelector("[data-job=claim]")?.click()');
  await until(() => !ctx.gameState.jobs[0] && js('!!document.querySelector(".reward-grid")'));
  const paid = ctx.gameState.coins;
  assert.equal(ctx.gameState.reports[0].breakdown.duplicates, 12);
  assert.equal(paid - before, ctx.gameState.reports[0].coins);
  assert.equal((await js('window.api.requestAction({type:"claim",jobId:' + JSON.stringify(original.id) + '})')).ok, true);
  assert.equal(ctx.gameState.coins, paid);
  await focusJobs(); await shot('06-result');
  // Reload both renderers; the result must survive and not be paid again.
  await Promise.all([g, p].map((contents) => new Promise((resolve) => { contents.once('did-finish-load', resolve); contents.reload(); })));
  await until(() => js('!!document.querySelector(".reward-grid")'));
  assert.equal(ctx.gameState.coins, paid);
  // Away mode returns when due without claiming; use debug placement only to avoid a long walk in tests.
  updateSettings({ jobMode: 'away' });
  await js('window.api.requestAction({type:"startJob",site:"yard"})');
  await until(() => ctx.gameState.jobs[0]);
  const awayJob = ctx.gameState.jobs[0];
  await scene('window.__excavator.state="away"; window.__excavator.sprite.setVisible(false); void 0');
  await replace({ ...ctx.gameState, jobs: [{ ...awayJob, start: Date.now() - 301_000, end: Date.now() - 1000 }] });
  await until(() => scene('window.__excavator.debugState().state === "return"'));
  await scene('window.__excavator.sprite.x = window.__excavator.targetX');
  await until(() => scene('window.__excavator.debugState().state === "waiting"'));
  assert(ctx.gameState.jobs[0]);
  assert.equal(ctx.gameState.coins, paid);
  assert.equal(errors.length, 0, errors.join('\n'));
  console.log('PASS Dispatch Electron: confirm, double-click guard, fixed equipment, timer, manual claim, failed-save UI, retry, breakdown, reload and away-mode return');
  if (!demo) {
    // New-machine guarantee: progress on the cards, the due job in the confirmation, and the marked result.
    updateSettings({ jobMode: 'stay' });
    await replace({ ...ctx.gameState, jobs: [], reports: [], xp: 4600, durability: 100, coins: 500, machinePity: { mine: 8, river: 3 } });
    await until(() => js('!!document.querySelector("[data-site=mine]") && !document.querySelector("[data-site=mine]").disabled'));
    const card = (id) => js(`document.querySelector("[data-site=${id}]").closest("article").textContent`);
    assert((await card('mine')).includes('新機型保底 8／9 · 本趟必得新機型'));
    assert((await card('river')).includes('新機型保底 3／10'));
    assert(!(await card('river')).includes('必得'));
    assert(!(await card('rail')).includes('新機型保底'));
    assert((await card('scrap')).includes('回收專長：重複零件按標價 50% 折現（10～50 金幣）'));
    assert(!(await card('quarry')).includes('回收專長'));
    await js('document.querySelector("[data-site=scrap]").closest("article").scrollIntoView({block:"center"})'); await shot('12-recycling-site');
    await js('document.querySelector("[data-site=scrap]").click()');
    assert(await js('document.querySelector("#job-confirm-body").textContent.includes("回收專長") && document.querySelector("#job-confirm-body").textContent.includes("50% 折現（10～50 金幣）")'));
    await shot('13-recycling-confirm');
    await js('document.querySelector("#job-back").click()');
    await js('document.querySelector("[data-site=mine]").closest("article").scrollIntoView({block:"center"})'); await shot('07-pity-site');
    await js('document.querySelector("[data-site=mine]").click()');
    assert(await js('document.querySelector("#job-confirm").open'));
    assert(await js('document.querySelector("#job-confirm-body").textContent.includes("本趟必得新機型") && document.querySelector("#job-confirm-body").textContent.includes("第 9 趟必定")'));
    await shot('08-pity-confirm');
    await js('document.querySelector("#job-depart").click()');
    await until(() => ctx.gameState.jobs[0] && js('!!document.querySelector("[data-job=cancel]")'));
    const pityJob = ctx.gameState.jobs[0];
    assert.equal(pityJob.rulesVersion, 4); assert.equal(pityJob.pity, 8);
    assert(await js('document.querySelector("#jobs").textContent.includes("本趟必得新機型")'));
    await replace({ ...ctx.gameState, jobs: [{ ...pityJob, start: Date.now() - 7_201_000, end: Date.now() - 1000, rolls: [0.5, 0.5, 0.99, 0.99, 0, 0.99, 0, 0.99, 0, 0.99, 0] }] });
    await until(() => js('!!document.querySelector("[data-job=claim]")'));
    await js('document.querySelector("[data-job=claim]").click()');
    await until(() => !ctx.gameState.jobs[0] && js('!!document.querySelector(".reward-grid")'));
    const machine = ctx.gameState.reports[0].drops.find((d) => d.id === 'm_mining');
    assert(machine && machine.pity, 'the guaranteed machine is marked');
    assert(ctx.gameState.owned.includes('m_mining'));
    assert.equal(ctx.gameState.machinePity.mine, undefined);
    assert(await js('document.querySelector(".job-report").textContent.includes("新機型 · 保底")'));
    await focusJobs(); await shot('09-pity-result');
    ctx.garageWin.setContentSize(380, originalSize[1]); await wait(150);
    assert(await js('document.documentElement.scrollWidth <= innerWidth'));
    await js('document.querySelector("[data-site=river]").closest("article").scrollIntoView({block:"center"})'); await shot('10-pity-narrow');
    nativeTheme.themeSource = 'dark'; await shot('11-pity-dark');
    nativeTheme.themeSource = 'light'; ctx.garageWin.setContentSize(...originalSize);
    assert.equal(errors.length, 0, errors.join(String.fromCharCode(10)));
    console.log('PASS Machine guarantee and recycling UI: per-site progress, scrap recycling note, due confirmation, fixed snapshot, marked result, narrow and dark layouts');

    // Two slots: buy the second, send a garage machine without touching the desktop, run two jobs, claim one.
    await replace({ ...ctx.gameState, jobs: [], reports: [], jobSlots: 1, coins: 1500, durability: 100, xp: 4600,
      owned: [...new Set([...ctx.gameState.owned, 'm_mini'])], equipped: { ...ctx.gameState.equipped, machine: 'm_std' } });
    await until(() => js('!!document.querySelector("[data-slot-buy]")'));
    assert(await js('document.querySelector("[data-slot-buy]").textContent.includes("花 1000 金幣解鎖")'));
    await js('window.confirm = () => true; document.querySelector("[data-slot-buy]").click()');
    await until(() => ctx.gameState.jobSlots === 2);
    assert.equal(ctx.gameState.coins, 500);
    assert(!(await js('!!document.querySelector("[data-slot-buy]")')));
    await js('const s = document.querySelector("#job-machine"); s.value = "m_mini"; s.dispatchEvent(new Event("change", { bubbles: true }))');
    assert.equal(await js('document.querySelector("#job-machine").value'), 'm_mini');
    assert(await js('document.querySelector("[data-site=quarry]").disabled'), 'the mini machine cannot work the quarry');
    await js('document.querySelector("[data-site=yard]").click()');
    assert(await js('document.querySelector("#job-confirm-body").textContent.includes("不影響桌面機型")'));
    await js('document.querySelector("#job-depart").click()');
    await until(() => ctx.gameState.jobs.length === 1);
    const [miniJob] = ctx.gameState.jobs;
    assert.equal(miniJob.machineId, 'm_mini'); assert.equal(miniJob.desktop, false);
    assert.equal(ctx.gameState.equipped.machine, 'm_std');
    assert.notEqual(await scene('window.__excavator.debugState().state'), 'working', 'a garage machine does not move the desktop pet');
    // the garage machine appears small beside the pet, works, and never takes the mouse
    await until(() => scene('window.__excavator.debugState().companion?.visible === true'));
    // it slides into place beside the pet; check once it has settled
    await until(async () => { const a = await scene('window.__excavator.debugState().companion.x'); await wait(150); return a === await scene('window.__excavator.debugState().companion.x'); });
    const companion = await scene('window.__excavator.debugState().companion');
    assert.equal(companion.jobId, miniJob.id);
    assert(companion.scale < await scene('window.__excavator.sprite.scaleX'), 'companion is drawn smaller than the pet');
    assert.equal(await scene(`window.__excavator.hitTest(${companion.x}, innerHeight - 8)`), false, 'clicks pass through the companion');
    await until(() => scene('/^(dig|dump|tinker)/.test(window.__excavator.debugState().companion.pose)'));
    await until(() => js('document.querySelector("#job-machine")?.value === "m_std"'));
    assert(await js('document.querySelector("[data-site=yard]").disabled && document.querySelector("[data-site=yard]").textContent.includes("已有工作進行中")'));
    await js('document.querySelector("[data-site=quarry]").click()');
    await js('document.querySelector("#job-depart").click()');
    await until(() => ctx.gameState.jobs.length === 2);
    assert.equal(ctx.gameState.jobs[1].desktop, true);
    await until(() => js('document.querySelectorAll(".mission-card").length === 2 && document.querySelector("#jobs").textContent.includes("所有工作槽都在使用中")'));
    await focusJobs(); await shot('14-slots-two-jobs');
    const petShot = async (name) => {
      const box = await scene('(() => { const a = window.__excavator.sprite.x, b = window.__excavator.debugState().companion.x; const l = Math.max(0, Math.min(a, b) - 170); return { x: Math.floor(l), y: Math.max(0, innerHeight - 240), width: Math.min(innerWidth - Math.floor(l), Math.abs(a - b) + 340), height: Math.min(240, innerHeight) }; })()');
      fs.writeFileSync(path.join(output, `${name}.png`), (await p.capturePage(box)).toPNG());
    };
    await petShot('16-desktop-companion');
    await replace({ ...ctx.gameState, jobs: [{ ...miniJob, start: Date.now() - 301_000, end: Date.now() - 1000 }, ctx.gameState.jobs[1]] });
    await until(() => js('document.querySelectorAll("[data-job=claim]").length === 1'));
    await until(() => scene('window.__excavator.debugState().companion?.label.includes("待領取")'));
    await petShot('17-desktop-companion-ready');
    await js('document.querySelector("[data-job=claim]").click()');
    await until(() => ctx.gameState.jobs.length === 1 && ctx.gameState.reports[0]?.jobId === miniJob.id);
    assert.equal(ctx.gameState.jobs[0].machineId, 'm_std');
    await until(() => scene('window.__excavator.debugState().companion === null'));
    assert(await js('document.querySelector(".job-report").open && document.querySelector(".job-report .reward-grid")'), 'the newest result shows even while another job is out');
    assert(await js('!!document.querySelector("#job-machine")'), 'a slot is free again');
    ctx.garageWin.setContentSize(380, originalSize[1]); await wait(150);
    assert(await js('document.documentElement.scrollWidth <= innerWidth'));
    await focusJobs(); await shot('15-slots-narrow');
    ctx.garageWin.setContentSize(...originalSize);
    assert.equal(errors.length, 0, errors.join(String.fromCharCode(10)));
    console.log('PASS Dispatch slots UI: buy second slot, garage machine leaves without moving the desktop, small click-through companion works and shows ready, busy site/machine, two jobs, claim one, narrow layout');
  }
  console.log(`Screenshots: ${output}`);
  if (demo) {
    updateSettings({ jobMode: 'stay' });
    ctx.garageWin.show(); ctx.garageWin.focus();
    await js(bannerScript('驗收演示 · 獨立測試存檔 · 可直接領取，不影響正式進度'));
    ctx.garageWin.setTitle('派遣驗收演示 — 不影響正式存檔');
    await focusJobs();
    console.log('Demo ready: a completed job is waiting for your manual claim. Close via the tray Quit command.');
  } else app.quit();
})().catch((err) => { console.error(err); app.exit(1); });
